#!/usr/bin/env bash
#
# Starts the primary Telegram MCP server (HTTP transport).
#
# Uses the existing, already-authorized session in ./tdlib-data.
# The token is read from .env so it survives restarts; if TG_HTTP_TOKEN is not
# set there, one is generated and written back.
#
# Usage:  ./start-primary.sh [--build]
#           --build   run the compiled output instead of tsx
#
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

PORT="${TG_HTTP_PORT:-8787}"
DB_DIR="${TDLIB_DB_DIR:-./tdlib-data}"
ENV_FILE=".env"
USE_BUILD=0
[[ "${1:-}" == "--build" ]] && USE_BUILD=1

# --- token: reuse the one in .env, or mint and persist a new one ------------
if [[ -f "$ENV_FILE" ]] && grep -qE '^TG_HTTP_TOKEN=.+' "$ENV_FILE"; then
  TOKEN="$(grep -E '^TG_HTTP_TOKEN=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '"'"'"' ')"
  echo "token: reusing TG_HTTP_TOKEN from $ENV_FILE"
else
  TOKEN="$(openssl rand -hex 32)"
  # Keep the token out of the shell history and stable across restarts.
  printf '\n# HTTP transport bearer token (generated by start-primary.sh)\nTG_HTTP_TOKEN=%s\n' \
    "$TOKEN" >> "$ENV_FILE"
  echo "token: generated and appended to $ENV_FILE"
fi

# --- refuse to start if something already owns the port or the database -----
if command -v ss >/dev/null 2>&1 && ss -tln 2>/dev/null | grep -q ":${PORT} "; then
  echo "ERROR: port ${PORT} is already in use." >&2
  echo "       Another server may be running: curl -s http://127.0.0.1:${PORT}/health" >&2
  exit 1
fi

# TDLib allows one process per database; a second one would bind the port and
# then fail every request, which is worse than not starting.
if pgrep -f "tsx src/http.ts|node dist/http.js" >/dev/null 2>&1; then
  echo "WARNING: another instance of this server is already running:" >&2
  pgrep -af "tsx src/http.ts|node dist/http.js" >&2 || true
  echo "         If it uses ${DB_DIR}, this one will fail with a database lock." >&2
  echo "         Press Ctrl-C to abort, or wait 5s to continue anyway." >&2
  sleep 5
fi

echo "───────────────────────────────────────────────"
echo " primary Telegram MCP server"
echo "   url:      http://127.0.0.1:${PORT}/mcp"
echo "   health:   http://127.0.0.1:${PORT}/health"
echo "   database: ${DB_DIR}  (existing login)"
echo "   token:    ${TOKEN:0:8}…  (full value in ${ENV_FILE})"
echo "───────────────────────────────────────────────"

export TG_HTTP_TOKEN="$TOKEN"
export TG_HTTP_PORT="$PORT"
export TDLIB_DB_DIR="$DB_DIR"

if [[ "$USE_BUILD" == "1" ]]; then
  [[ -f dist/http.js ]] || npm run build
  exec node dist/http.js
else
  exec npx tsx src/http.ts
fi

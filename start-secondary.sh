#!/usr/bin/env bash
#
# Starts a SECOND, independent Telegram MCP server (HTTP transport).
#
# It uses its own port and its own TDLib database, so it can run alongside the
# primary. TDLib locks its database exclusively, so a separate directory is
# mandatory rather than optional.
#
# NOTE: a fresh database starts UNAUTHORIZED. After the first launch, log in
# via the tg_login tool - normally with a *different* Telegram account. Do not
# copy tdlib-data/ to clone a login; those are live session keys and the copies
# invalidate each other.
#
# Usage:  ./start-secondary.sh [--build]
#
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

PORT="${TG_HTTP_PORT:-8789}"
DB_DIR="${TDLIB_DB_DIR:-./tdlib-data-2}"
ENV_FILE=".env.secondary"
USE_BUILD=0
[[ "${1:-}" == "--build" ]] && USE_BUILD=1

# Guard against pointing both servers at one database.
PRIMARY_DB="$(cd "$(dirname "${TDLIB_DB_DIR:-./tdlib-data}")" 2>/dev/null && pwd)/$(basename "${TDLIB_DB_DIR:-./tdlib-data}")"
RESOLVED_DB="$(cd "$(dirname "$DB_DIR")" 2>/dev/null && pwd)/$(basename "$DB_DIR")"
if [[ "$RESOLVED_DB" == "$(pwd)/tdlib-data" ]]; then
  echo "ERROR: the secondary server must not use ./tdlib-data - that is the primary's" >&2
  echo "       database and TDLib permits only one process per database." >&2
  echo "       Set TDLIB_DB_DIR to something else (default: ./tdlib-data-2)." >&2
  exit 1
fi

# --- token: separate from the primary's, persisted in its own file ----------
if [[ -f "$ENV_FILE" ]] && grep -qE '^TG_HTTP_TOKEN=.+' "$ENV_FILE"; then
  TOKEN="$(grep -E '^TG_HTTP_TOKEN=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '"'"'"' ')"
  echo "token: reusing TG_HTTP_TOKEN from $ENV_FILE"
else
  TOKEN="$(openssl rand -hex 32)"
  printf '# Bearer token for the secondary MCP server (generated by start-secondary.sh)\nTG_HTTP_TOKEN=%s\n' \
    "$TOKEN" > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "token: generated and written to $ENV_FILE"
fi

if command -v ss >/dev/null 2>&1 && ss -tln 2>/dev/null | grep -q ":${PORT} "; then
  echo "ERROR: port ${PORT} is already in use. Set TG_HTTP_PORT to a free port." >&2
  exit 1
fi

IS_NEW=0
[[ -f "${DB_DIR}/td.binlog" ]] || IS_NEW=1

echo "───────────────────────────────────────────────"
echo " secondary Telegram MCP server"
echo "   url:      http://127.0.0.1:${PORT}/mcp"
echo "   health:   http://127.0.0.1:${PORT}/health"
echo "   database: ${DB_DIR}"
echo "   token:    ${TOKEN:0:8}…  (full value in ${ENV_FILE})"
if [[ "$IS_NEW" == "1" ]]; then
  echo
  echo "   This database is NEW, so the server starts UNAUTHORIZED."
  echo "   Log in through the tg_login tool:"
  echo "     tg_login {\"action\":\"status\"}"
  echo "     tg_login {\"action\":\"phone\",\"phone_number\":\"+…\"}"
  echo "     tg_login {\"action\":\"code\",\"code\":\"12345\"}"
  echo "   Use a different Telegram account than the primary."
fi
echo "───────────────────────────────────────────────"

export TG_HTTP_TOKEN="$TOKEN"
export TG_HTTP_PORT="$PORT"
export TDLIB_DB_DIR="$DB_DIR"

if [[ "$USE_BUILD" == "1" ]]; then
  [[ -f dist/http.js ]] || npm run build
  exec node dist/http.js
else
  exec npx tsx src/http.ts
fi
